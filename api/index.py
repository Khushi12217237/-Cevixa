FEATURES = ['pm_f0_median_hz', 'pm_jitter_local_pct', 'pm_shimmer_local_pct', 'pm_hnr_db']
MIN_SPREAD = {'pm_f0_median_hz': 0.03, 'pm_jitter_local_pct': 0.15, 'pm_shimmer_local_pct': 0.10, 'pm_hnr_db': 0.05}
Z_LIMIT, NEED_FEATURES, BASELINE_DAYS = 3.0, 2, 7

def add_voice_scores(df):
    out = []
    for pid, g in df.groupby('patient_id'):
        g = g.sort_values('day').copy()
        g['segment'] = (g.phone_model != g.phone_model.shift()).cumsum()
        g['segment_day'] = g.groupby('segment').cumcount() + 1
        for f in FEATURES:
            g['z_' + f] = np.nan
        for seg, gs in g.groupby('segment'):
            base = gs[(gs.segment_day <= BASELINE_DAYS) & gs.quality_ok]
            if len(base) < 5:
                continue
            for f in FEATURES:
                med = base[f].median()
                mad = 1.4826 * (base[f] - med).abs().median()
                spread = max(mad, MIN_SPREAD[f] * abs(med))
                g.loc[gs.index, 'z_' + f] = np.where(gs.quality_ok, (gs[f] - med) / spread, np.nan)
        zcols = ['z_' + f for f in FEATURES]
        g['n_beyond'] = (g[zcols].abs() > Z_LIMIT).sum(axis=1)
        hit = (g.n_beyond >= NEED_FEATURES) & g.quality_ok & (g.segment_day > BASELINE_DAYS)
        g['voice_flag'] = hit & hit.groupby(g.segment).shift(1, fill_value=False)
        out.append(g)
    return pd.concat(out)

def add_weight_flags(df):
    parts = []
    for pid, g in df.groupby('patient_id'):
        g = g.sort_values('day').copy()
        w = g.set_index('day')['weight_kg'].reindex(range(1, int(g.day.max()) + 1))
        g['weight_delta_24h'] = g.day.map(w.diff())          # khaali agar kal ka weight nahi
        g['weight_delta_7d'] = g.day.map(w - w.shift(7))
        g['weight_flag'] = ((g.weight_delta_24h >= 1.4) | (g.weight_delta_7d >= 2.3)).fillna(False)
        parts.append(g)
    return pd.concat(parts)

