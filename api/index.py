import parselmouth
from parselmouth.praat import call

def voice_numbers(path, f0min=75, f0max=300):
    snd = parselmouth.Sound(path)
    snd = snd.extract_part(from_time=0.7, to_time=snd.duration - 0.2, preserve_times=False)
    pitch = call(snd, 'To Pitch', 0.0, f0min, f0max)
    f0_median = call(pitch, 'Get quantile', 0, 0, 0.5, 'Hertz')
    pp = call(snd, 'To PointProcess (periodic, cc)', f0min, f0max)
    jitter = call(pp, 'Get jitter (local)', 0, 0, 0.0001, 0.02, 1.3) * 100
    shimmer = call([snd, pp], 'Get shimmer (local)', 0, 0, 0.0001, 0.02, 1.3, 1.6) * 100
    hnr = call(call(snd, 'To Harmonicity (cc)', 0.01, f0min, 0.1, 1.0), 'Get mean', 0, 0)
    return {'f0_median_hz': f0_median, 'jitter_local_pct': jitter, 'shimmer_local_pct': shimmer, 'hnr_db': hnr}

