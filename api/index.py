def message(r):
    bits = []
    if r.weight_flag: bits.append('weight change')
    if r.voice_flag: bits.append('voice change vs own baseline')
    if bits:
        m = 'REVIEW SUGGESTED: ' + ' + '.join(bits)
        if r.voice_flag and r.cold_cough_today == 1:
            m += ' (cold or cough reported today: interpret with care)'
        return m
    if not r.quality_ok:
        return 'NO USABLE VOICE (' + str(r.quality_reason) + ')'
    if r.segment_day <= BASELINE_DAYS:
        return 'Building voice baseline (day %d of %d)' % (r.segment_day, BASELINE_DAYS)
    return 'No flag today (this does not mean the patient is well)'

result['message'] = result.apply(message, axis=1)
